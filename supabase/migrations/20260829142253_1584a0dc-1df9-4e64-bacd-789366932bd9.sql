A three-day workshop costs less than almost anything else a foundation can fund. That is precisely why so many are funded, and why so few are followed up. We followed twenty-two participants from a tailoring and repair workshop for twelve months, and the arithmetic that emerged was not the arithmetic in the original proposal.

## The costs the proposal counted

The budget covered a trainer, materials, three days of venue hire, and refreshments. Divided across twenty-two participants, the per-person figure was small enough to be quoted approvingly in two subsequent funding conversations.

## The costs the participants paid

Participants absorbed a second budget that appeared nowhere in ours.

- **Three days of forgone earnings**, which for eleven of the twenty-two exceeded the entire per-person cost of running the workshop.
- **Childcare**, arranged informally, and the reciprocal obligation it created.
- **Transport**, trivial per trip and non-trivial across six trips including the follow-up sessions.
- **Start-up capital afterwards** — the single largest figure, and the one nobody had planned for.

That last item is where most skills training quietly fails. A participant finishes competent and cannot act on the competence because the tools cost more than a month of household surplus. Training without a path to equipment produces skilled people with no change in income, which is a worse outcome than it sounds: it produces skilled people who now know exactly what they cannot afford to do.

> The workshop was not the intervention. The workshop plus access to a sewing machine was the intervention. We had funded half of something.

## What happened over twelve months

Of twenty-two participants:

- **Six** were earning regularly from the skill at month twelve. All six had access to equipment within the first eight weeks — four through a household member, two through a shared machine arrangement that emerged spontaneously.
- **Five** were earning occasionally and irregularly, mostly repairs for neighbours, with no tools of their own.
- **Nine** were not using the skill at all. Seven of those nine named equipment as the reason without prompting.
- **Two** could not be contacted.

Read one way, that is a twenty-seven per cent success rate and an unimpressive programme. Read another way, it is a near-total success among the subgroup that could act, and a design failure for everyone else — a failure we could have identified in week one by asking a single question about equipment access.

## The shared-machine finding

The most interesting result was not planned. Two participants pooled resources to buy one machine and alternate days. A year on, both are earning, and the arrangement has extended to a third person.

This suggests the binding constraint is not ownership but access, and that access can be manufactured at roughly a third of the cost of provision. Our current pilots test three variants: a machine held at a community space with a booking sheet, a matched-savings scheme toward shared purchase, and a rental-to-own arrangement through an existing local business. It is too early to report results, and we will publish them either way.

## Selection matters more than curriculum

The strongest single predictor of a participant earning at month twelve was not aptitude, attendance or prior experience. It was whether they had already attempted income-generating work of any kind in the previous year.

This is uncomfortable, because it implies that the training works best for people who were already closest to the outcome — and that reaching the people furthest from it requires a different and more expensive intervention, not the same workshop with better outreach. Programmes that report strong outcomes while quietly selecting for readiness are not lying; they are describing a narrower achievement than the headline suggests.

We now state our selection criteria publicly and report outcomes split by prior experience. The overall numbers look worse. The numbers are more useful.

## Follow-up is where the budget should go

The workshop consumed roughly seventy per cent of the programme cost and produced most of the visible activity. The follow-up — four short check-ins over six months, mostly by phone — consumed under ten per cent and accounted for every case where a stalled participant restarted.

If we ran this again, the split would invert. Two days of training, and the remainder spent on nine months of contact, equipment access and problem-solving. The training is the cheap part. The year afterwards is the programme.

## What we now tell funders

Three days of instruction reliably produces three days of instruction. Whether it produces income depends almost entirely on things that happen after the certificate: tools, contact, and a first customer. Any proposal that costs out the workshop and not the year afterwards is costing out the wrong thing — and we have written several of them ourselves.

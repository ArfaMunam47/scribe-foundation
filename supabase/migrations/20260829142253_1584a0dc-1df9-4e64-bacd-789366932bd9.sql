Tree planting is one of the easiest things to fund and one of the hardest to sustain. Planting days are popular, photogenic and cheap. Survival rates, where anyone measures them, are frequently below half at eighteen months. The gap is not a horticultural problem. It is a maintenance and ownership problem, and it is worth being blunt about that before describing what we found.

## Shade is a service, not a decoration

Across two summers we took surface and air temperature readings at nine points in one neighbourhood at three fixed times of day. The difference between a shaded and an unshaded stretch of the same street was substantial enough to change behaviour rather than merely comfort.

The behavioural findings mattered more than the thermal ones:

- **Footfall** along the shaded stretch during the hottest three hours ran roughly double the unshaded stretch, despite the two routes serving the same destinations.
- **Two vendors relocated** their stalls to the shaded side within a season, without prompting.
- **Waiting behaviour changed**: people arriving early for the clinic waited outside under trees rather than crowding the entrance, which the clinic staff raised with us independently.
- **The primary school** reported that children lingered after dismissal instead of dispersing immediately, which parents described as convenient and staff described as a supervision question.

None of this appears in a beautification framing. All of it is the kind of thing a transport or health budget line is meant to deliver.

> A street tree is a piece of public infrastructure that happens to be alive. Fund it like the first thing and maintain it like the second.

## Why plantings fail

Our own losses, categorised honestly:

1. **Watering gap in the first dry season.** The dominant cause. Enthusiasm reliably outlasts the planting day and reliably does not outlast eight weeks.
2. **No named owner.** Trees planted on a boundary — between two properties, two authorities, or two lanes — died at markedly higher rates than trees with an adjacent household that considered them theirs.
3. **Physical damage.** Goats, vehicles, and construction. Guards cost a fraction of a replacement sapling and were omitted from our first two rounds to save money.
4. **Species chosen for growth rate.** Fast species produced shade quickly and then produced root damage, complaints and removals. Slower, locally established species have outperformed them over five years on every measure except the first eighteen months.

## The adoption model

The change that moved survival from under half to above eighty per cent was administrative rather than technical: every sapling is assigned to a specific household or business at planting, by name, recorded on a list that is posted publicly.

Adopters receive a bucket, a written watering schedule for the first dry season, and a visit at weeks two, six and twelve. That is the entire intervention. It costs a small amount per tree and it works because it converts a diffuse public good into a specific person's responsibility, visible to their neighbours.

Where no household will adopt a location, we no longer plant there. Empty positions on the list are more useful than dead saplings, and they tell us something about the street.

## Budgeting for years two and three

The standard planting grant funds saplings, tools and a day of labour. It funds nothing in year two, which is when pruning, replacement and the second dry season occur.

Our current costing includes three years as a single item, with roughly forty per cent of the total falling after the planting day. This makes the proposal look more expensive than comparable ones. It is the same programme, honestly priced; the cheaper-looking versions are simply deferring the cost onto whoever inherits a street of struggling trees.

## What we would tell another organisation

- Count survival at eighteen months, not at planting. Publish both numbers.
- Assign every tree to a named person before the sapling arrives.
- Buy the guards. The saving from omitting them is illusory.
- Choose species with people who have lived on the street for twenty years, not from a catalogue.
- Plant fewer trees than the budget allows and maintain all of them, rather than the reverse.

## The longer view

The oldest planting we are involved with is now seven years old and no longer requires anything from us. It shades a stretch of road used by several hundred people a day, it has changed where a market operates, and its maintenance is handled entirely by the households along it.

It cost less than a single year of most programmes we run. It is the closest thing to permanence in our portfolio, and it arrived through a mechanism no more sophisticated than a bucket, a list of names, and three visits.

We give small grants — typically enough to cover a year of modest operating costs for a group of two to six people. We think it is among the more useful things we do, and we also think the sector describes small grants inaccurately, usually in our own favour. This is an attempt at a more honest account.

## What a small grant actually costs the recipient

The application takes a day, sometimes two. Reporting takes a further two or three days across the year. For a group of three people running a service, that is roughly one per cent of their total available working time spent on us, before any of the informal labour of hosting visits, answering queries and attending convenings.

Against a grant of meaningful size, that is a reasonable trade. Against a small grant it is often not, and the smaller the grant the worse the ratio becomes. A funder offering a token amount with full reporting requirements is transferring administrative cost to the least resourced party in the arrangement.

Our response has been to set a floor. Below a certain amount we make the payment with a one-paragraph request and no formal report, and we accept that this reduces what we know. The alternative — extracting a full report for a sum that does not justify writing one — is worse.

> If the reporting burden is a meaningful fraction of the grant's value, the grant is smaller than it appears.

## What we require, and why

For grants above the floor, we ask for three things and deliberately not more.

1. **A short mid-year conversation**, not a written interim report. Twenty minutes on a call surfaces more than four pages, and it surfaces problems earlier because nobody is committing them to a document.
2. **A final note of no more than two pages**, in whatever structure suits the group, answering what happened, what changed, and what they would do differently.
3. **Notification if the plan changes substantially** — not for approval, but because a grantee quietly delivering something different from the proposal is usually a sign they learned something we would like to know.

We do not require receipts for every line, budget variance explanations, or beneficiary counts. We have found that the effort spent producing those figures is rarely repaid by their accuracy.

## Multi-year, unrestricted, boring

The three features of funding that grantees consistently rate highest are also the three that funders find hardest to describe in an annual report: money over more than one year, money without restriction, and money that arrives when it was promised.

Late disbursement is the most damaging and the least discussed. A group that has hired someone on the strength of a confirmed grant and then waits eleven weeks for the transfer has been handed a cash-flow crisis by its supporter. We now treat a missed disbursement date as an incident to be recorded internally, in the same category as any other operational failure. We have recorded four.

Unrestricted funding attracts the objection that it is unaccountable. In our experience the opposite happens: groups given unrestricted money account for it more candidly, because they are not obliged to retrofit their real spending into categories agreed a year earlier.

## Selection, and its blind spots

We select through a combination of open application and referral. Both channels have distortions worth stating.

Open applications favour groups with someone who writes well in the language of the sector — a skill unevenly distributed and essentially unrelated to whether a group is good at its work. Referrals favour groups already connected to our existing network, which compounds over time into a portfolio that looks more homogeneous each year.

We now review the portfolio annually against a simple question: which kinds of organisation have we not funded, and is that because they do not exist, because they did not apply, or because our process filtered them out? The third answer has come up more often than we would like.

## What we have got wrong

**We have funded projects rather than organisations.** Project funding leaves a group with a delivered activity and no capacity to sustain it. Several of our early grants produced good work that stopped the day the money did.

**We have asked for scale too early.** Twice we encouraged a group to expand before their core operation was stable, and both times the expansion consumed the attention that was holding the original work together.

**We have been slow to end things.** Continuing to fund a group whose work has drifted is easier than the conversation, and the delay helps nobody. We now schedule an explicit continue-or-conclude decision at the end of each grant period so that ending is a normal outcome rather than a rebuke.

## The horizon that matters

The work we fund operates on timescales of years. Grant cycles operate on timescales of months. Most of the friction in small-grant funding comes from that mismatch, and most of it is ours to absorb rather than theirs.

Our current commitment is simple: longer terms, fewer conditions, payments on the date we said, and an honest annual account — including the parts that did not work.

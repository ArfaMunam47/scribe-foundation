The gate was supposed to open at nine. By twenty past eight there were around forty people outside, most of them holding the printed slip from the school, several of them holding it the wrong way up because the printing had run out halfway through the batch. Somebody had already begun an informal queue, enforced by nothing except the general agreement that there should be one.

These are notes from that day, kept as they happened and edited only for names.

## Before nine

The chairs arrive late, which is normal. The tea arrives early, which is not, and the volunteer who brought it becomes for the next hour the most important person on site. Two things about that are worth recording: the tea kept the queue in good humour through a delay that would otherwise have soured it, and nobody had budgeted for the tea. It came out of somebody's pocket.

The registration table is positioned facing the gate, which means the first thing anyone encounters is a form. By half past nine we have moved it to the side and put the information stall in front instead. Registration numbers do not fall. The atmosphere at the entrance changes completely.

## The stall nobody visited

Six stalls. Five busy from the first hour. One — the one presenting our own programme information, with the printed materials and the display boards and the two staff members in branded shirts — receives eleven visitors all day, most of whom appear to be looking for the toilets.

It is worth being precise about why. It was staffed by people nobody recognised, it offered no reason to stop, and it required a visitor to declare interest in front of a queue of neighbours. The stall next to it was cutting and distributing seedlings, and it had a permanent crowd. People will talk to you at length while their hands are busy. They will not walk up to a table to be informed.

> Every conversation of value that day happened alongside an activity. None happened across a table.

## What came up, repeatedly

Keeping a rough tally of what people raised unprompted:

- **Timing of the after-school sessions** — raised nine times, always the same complaint, always the collection time rather than the content.
- **Whether the water point repair was actually happening** — raised seven times, with a level of scepticism that our previous communication had clearly earned.
- **Requests for adult literacy provision** — raised six times, entirely by people over forty, and not something we currently offer anywhere.
- **The cost of school materials in the third term** — raised five times, in every case as a household budgeting problem rather than an education one.

Two of these changed programme decisions within a month. The collection time moved. A small adult literacy pilot is now scheduled, deliberately in the evening, deliberately in a room that is not the school.

## The conversation by the wall

An older man, standing apart from everything for most of the morning, eventually explains that he had attended a similar day eleven years ago, run by a different organisation, and that nothing announced at it had happened. He is not angry. He is explaining, patiently, why his neighbours' enthusiasm should be read cautiously.

This is the most useful twenty minutes of the day. It is also a reminder that a community's response to us is shaped by a history we did not participate in and mostly do not know. The correct response is not reassurance. It is to make fewer announcements and to publish what happened to the last ones.

## Numbers, and what they are worth

Around three hundred and ten people through the gate. Ninety-four registrations. Twenty-six volunteer sign-ups, of which — following the pattern we now expect — perhaps ten will convert into an actual first shift if we make contact this week and considerably fewer if we do not.

The number we care about more will not be visible until the third week of next term: how many of the ninety-four are still attending anything.

## Four practical corrections

1. Print more slips than you need, and check the toner.
2. Put an activity where you were going to put an information table.
3. Budget for the tea.
4. Contact volunteer sign-ups within forty-eight hours, before the day stops feeling recent.

## At four o'clock

The stall holders pack down faster than they set up, which is universal. A group of teenagers stays behind to move chairs without being asked, which is the sort of thing that never appears in a report and is probably the clearest signal of the day that the room was theirs.

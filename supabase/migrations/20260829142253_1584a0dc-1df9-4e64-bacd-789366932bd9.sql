This is a standing note about how the foundation operates. It exists because we ask communities and grantees for candour about their work, and that request is difficult to justify without being specific about our own. It is updated when practice changes rather than on a fixed schedule, and previous versions remain available on request.

## Governance

The foundation is directed by a board that meets quarterly and holds decision-making authority over strategy, budget approval and senior appointments. Day-to-day operations are delegated to the executive team.

Board members serve fixed terms with a limit on consecutive renewals. At least one seat is reserved for a person with direct lived experience of the areas in which we work, and that seat carries the same vote as every other. Members declare interests annually and recuse themselves from decisions where a conflict exists; recusals are recorded in the minutes.

Minutes of board decisions — not full discussions — are published in summary. Where a matter is withheld, we state that a matter was withheld and the category of reason, rather than omitting it silently.

## How decisions about money are made

Grant and programme decisions above a defined threshold require board approval. Below that threshold they are made by the executive team against published criteria, and reported to the board in aggregate.

Three commitments govern disbursement:

- **Payment on the date agreed.** A missed date is recorded internally as an operational failure and reported to the board.
- **No restriction beyond what the grant purpose requires.** We do not attach conditions we would not want attached to us.
- **A stated decision on continuation** at the end of every grant period, so that concluding a relationship is a normal outcome rather than an implied judgement.

Accounts are independently examined annually and published in full, including administrative and staff costs as separate lines. We do not report a single "overheads" percentage, because the figure is easy to manipulate and tells a reader very little.

## Editorial practice

The articles published here are written by staff and by people working directly on the programmes described. We publish for three reasons: to record what happened, to make our reasoning available for criticism, and to be useful to organisations doing similar work.

Our standing rules:

1. **We name what did not work.** An account containing no failures is a marketing document.
2. **We do not use identifying details of individuals without informed consent**, given in the person's own language, with an explanation of where the piece will appear.
3. **We do not photograph people in distress**, and we do not use images of children where the child is identifiable and the image is not essential to the story.
4. **Numbers are presented with their denominators**, and estimates are labelled as estimates.
5. **We distinguish observation from inference** in the text, particularly where we are drawing conclusions from small samples — which is often.

Articles are reviewed by at least one person not involved in the work described. Where a piece discusses a partner organisation, that organisation sees it before publication and may correct facts, though not conclusions.

## Corrections

We correct errors of fact promptly and visibly. A corrected article carries a dated note at the foot describing what was changed. We do not silently edit published text, and we do not remove articles that have become inconvenient; where a position has changed, we publish the change alongside the original.

Corrections can be requested by writing to the editorial address on the contact page. We aim to respond within five working days and to state plainly when we disagree.

## Data and privacy

We collect the minimum information needed to run a service, we say what it is for at the point of collection, and we do not share personal data with third parties for any purpose other than delivering the service concerned.

Newsletter subscriptions are single-purpose and can be ended from any message we send. Contact form submissions are retained for a limited period and then deleted. Accounts created on this site store an email address and an optional display name; account holders can request deletion at any time and we act on it rather than deactivating.

## Safeguarding and complaints

We maintain a safeguarding policy covering all staff, volunteers and partners, with mandatory briefing before any work involving children or vulnerable adults. Concerns can be raised confidentially and are handled by a named person outside the relevant programme's management line.

Complaints about our conduct are logged, acknowledged within five working days, and reported to the board in aggregate each quarter, including the number upheld.

## What we are still working on

Three areas of our own practice are not yet where we would like them.

Our published outcome data lags our internal data by several months, which is a capacity problem rather than a policy one. Our board remains less representative of the communities we work with than we intend, despite the reserved seat. And our grant reporting requirements, though lighter than sector norms, are still heavier than the smallest grants justify.

We record these here because a statement of practice that lists only settled matters is not a statement of practice. It is an advertisement.
